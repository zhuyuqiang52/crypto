class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=5000):
        super(PositionalEncoding, self).__init__()
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        self.register_buffer('pe', pe.unsqueeze(0))

    def forward(self, x):
        x = x + self.pe[:, :x.size(1)]
        return x

class SeriesTransformerEncoder(nn.Module):
    def __init__(self, input_dim=2, d_model=64, nhead=8, num_layers=4, output_dim=32, seq_len=168):
        super().__init__()
        self.input_linear = nn.Linear(input_dim, d_model)
        self.pos_encoder = PositionalEncoding(d_model, max_len=seq_len)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead, dim_feedforward=d_model*4, batch_first=True)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.output_linear = nn.Linear(d_model, output_dim)
        
    def forward(self, x):
        x = self.input_linear(x)
        x = self.pos_encoder(x)
        x = self.transformer_encoder(x)
        x = x.mean(dim=1)
        x = self.output_linear(x)
        return x

class BiEncoderModel(nn.Module):
    def __init__(self, num_factors, d_model=64, nhead=8, num_layers=4, embed_dim=32, final_dim=64):
        super().__init__()
        self.hourly_encoder = SeriesTransformerEncoder(input_dim=2, d_model=d_model, nhead=nhead, num_layers=num_layers, output_dim=embed_dim, seq_len=168)
        self.minute_encoder = SeriesTransformerEncoder(input_dim=2, d_model=d_model, nhead=nhead, num_layers=num_layers, output_dim=embed_dim, seq_len=120)
        
        self.fc_factors = nn.Sequential(
            nn.Linear(num_factors, 64),
            nn.ReLU(),
            nn.Linear(64, embed_dim)
        )
        
        # Modality Fusion Encoder
        fusion_layer = nn.TransformerEncoderLayer(d_model=embed_dim, nhead=4, dim_feedforward=embed_dim*4, batch_first=True)
        self.fusion_encoder = nn.TransformerEncoder(fusion_layer, num_layers=2)
        
        # Final projection
        self.fc_final = nn.Sequential(
            nn.Linear(embed_dim, 128),
            nn.ReLU(),
            nn.Linear(128, final_dim)
        )
        
    def forward(self, h_seq, m_seq, f_vec):
        h_emb = self.hourly_encoder(h_seq)
        m_emb = self.minute_encoder(m_seq)
        f_emb = self.fc_factors(f_vec)
        
        # Stack into sequence for the fusion encoder: (batch, 3, embed_dim)
        stacked_emb = torch.stack([h_emb, m_emb, f_emb], dim=1)
        
        fused_seq = self.fusion_encoder(stacked_emb)
        fused_emb = fused_seq.mean(dim=1)
        
        final_emb = self.fc_final(fused_emb)
        return final_emb

