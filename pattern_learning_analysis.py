print("Starting Triplet-Loss Bi-Encoder training...")

for epoch in range(epochs):
    model.train()
    epoch_loss = 0
    for anchor, positive, negative in train_dataloader:
        a_h, a_m, a_f = [t.to(device) for t in anchor]
        p_h, p_m, p_f = [t.to(device) for t in positive]
        n_h, n_m, n_f = [t.to(device) for t in negative]
        
        optimizer.zero_grad()
        
        anchor_emb = model(a_h, a_m, a_f)
        pos_emb = model(p_h, p_m, p_f)
        neg_emb = model(n_h, n_m, n_f)
        
        loss = criterion(anchor_emb, pos_emb, neg_emb)
        
        loss.backward()
        optimizer.step()
        
        epoch_loss += loss.item()
    
    print(f"Epoch {epoch+1}/{epochs}, Triplet Loss: {epoch_loss/len(train_dataloader):.4f}")

