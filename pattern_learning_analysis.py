class CryptoTripletDataset(Dataset):
    def __init__(self, times, hourly_arr, min_arr, factor_arr, hourly_idx, min_idx, factor_idx, t_to_tgt):
        self.times = times
        self.hourly_arr = hourly_arr
        self.min_arr = min_arr
        self.factor_arr = factor_arr
        self.hourly_idx = hourly_idx
        self.min_idx = min_idx
        self.factor_idx = factor_idx
        
        self.targets = np.array([t_to_tgt[t] for t in times])
        norms = np.linalg.norm(self.targets, axis=1, keepdims=True)
        self.norm_targets = self.targets / (norms + 1e-8)
        
    def __len__(self):
        return len(self.times)
        
    def _get_tensors(self, i):
        t = self.times[i]
        h_i = self.hourly_idx[t]
        m_i = self.min_idx[t]
        f_i = self.factor_idx[t]
        
        h_seq = self.hourly_arr[h_i - 167 : h_i + 1]
        m_seq = self.min_arr[m_i - 119 : m_i + 1]
        f_vec = self.factor_arr[f_i]
        
        return (torch.FloatTensor(h_seq), 
                torch.FloatTensor(m_seq), 
                torch.FloatTensor(f_vec))
                
    def __getitem__(self, i):
        anchor = self._get_tensors(i)
        
        # Dynamic Positive/Negative mining based on Cosine Similarity
        # Sub-sample 50 candidates dynamically to keep memory/CPU low
        cand_indices = np.random.choice(len(self.times), min(50, len(self.times)), replace=False)
        sims = np.dot(self.norm_targets[cand_indices], self.norm_targets[i])
        
        pos_idx = cand_indices[np.argmax(sims)]
        neg_idx = cand_indices[np.argmin(sims)]
        
        positive = self._get_tensors(pos_idx)
        negative = self._get_tensors(neg_idx)
        
        return anchor, positive, negative

